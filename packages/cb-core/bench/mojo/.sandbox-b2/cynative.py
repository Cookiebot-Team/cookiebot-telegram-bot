def _bench_textmatch(iterations: cython.Py_ssize_t) -> cython.double:
    samples: list = [
        "/dice@CookieMWbot 20",
        "/shippar @someone",
        "hello everyone, nothing to see here",
        "look https://bsky.app/profile/x/post/123 nice",
        "/d20",
    ]
    bot: str = "CookieMWbot"
    best: cython.double = 1e30
    r: cython.Py_ssize_t
    i: cython.Py_ssize_t
    sink: cython.Py_ssize_t
    ns: cython.double
