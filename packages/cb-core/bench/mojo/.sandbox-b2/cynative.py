@cython.cclass
class TokenBucket:
    """Classic token bucket. `capacity` burst, refilled at `rate` tokens/second."""

    capacity: cython.double
    rate: cython.double
    _tokens: cython.double
    _last: cython.double

    def __init__(self, capacity: float, rate: float, now: float = 0.0) -> None:
        self.capacity = capacity
        self.rate = rate
        self._tokens = capacity
        self._last = now

    @cython.ccall
    def allow(self, now: cython.double, cost: cython.double = 1.0) -> cython.bint:
        elapsed: cython.double = now - self._last
        tokens: cython.double
        if elapsed > 0.0:
            self._last = now
            tokens = self._tokens + elapsed * self.rate
            self._tokens = tokens if tokens < self.capacity else self.capacity
        if self._tokens >= cost:
            self._tokens -= cost
            return True
        return False

    @cython.ccall
    def retry_after(self, cost: cython.double = 1.0) -> cython.double:
        """Seconds until `cost` tokens are available. 0 if available now."""
        deficit: cython.double = cost - self._tokens
        if deficit <= 0.0:
            return 0.0
        if self.rate <= 0.0:
            return float("inf")
        return deficit / self.rate

    @property
    def tokens(self) -> float:
        return self._tokens


@cython.cclass
class SlidingWindow:
    """Bounded sliding-window counter for sticker spam (`core_stickerspam`).

    Older entries fall out of the window instead of accumulating forever the way
    v1's dicts did, and a flood is hard-capped.
    """

    limit: cython.Py_ssize_t
    window: cython.double
    _stamps: list

    def __init__(self, limit: int, window: float) -> None:
        self.limit = limit
        self.window = window
        self._stamps = []

    @cython.ccall
    def hit(self, now: cython.double) -> cython.Py_ssize_t:
        """Record an event; return the count inside the window (post-insert)."""
        cutoff: cython.double = now - self.window
        stamps: list = self._stamps
        drop: cython.Py_ssize_t = 0
        n: cython.Py_ssize_t = len(stamps)
        cap: cython.Py_ssize_t = self.limit * 4
        while drop < n and stamps[drop] <= cutoff:
            drop += 1
        if drop > 0:
            del stamps[:drop]
        stamps.append(now)
        n = len(stamps)
        if n > cap:
            del stamps[: n - cap]
            n = cap
        return n

    @cython.ccall
    def exceeded(self, now: cython.double) -> cython.bint:
        return self.hit(now) > self.limit

    def reset(self) -> None:
        self._stamps.clear()

    @property
    def count(self) -> int:
        return len(self._stamps)


@cython.cclass
class QuotaLedger:
    """Per-key daily quota (AI replies, image searches) with explicit day rollover.

    v1 relied on detecting a date change inside the message handler and then
    clearing a dict; a restart silently refilled everyone's quota.
    """

    limit: cython.Py_ssize_t
    _used: dict
    _day: cython.long

    def __init__(self, limit: int) -> None:
        self.limit = limit
        self._used = {}
        self._day = -1

    @cython.ccall
    def take(
        self, key: cython.longlong, day_ordinal: cython.long, cost: cython.Py_ssize_t = 1
    ) -> cython.bint:
        used: cython.Py_ssize_t
        if day_ordinal != self._day:
            self._day = day_ordinal
            self._used.clear()
        used = self._used.get(key, 0)
        if used + cost > self.limit:
            return False
        self._used[key] = used + cost
        return True

    @cython.ccall
    def remaining(self, key: cython.longlong, day_ordinal: cython.long) -> cython.Py_ssize_t:
        if day_ordinal != self._day:
            return self.limit
        return self.limit - self._used.get(key, 0)

# ==================== dedupe.py

"""Update deduplication and media fingerprinting — hot path, Cython-compiled.

Telegram redelivers webhook updates on any non-2xx, so dedupe is mandatory.
v1 kept two unbounded sets and, at 10 000 entries, called `.clear()` — dropping
every id at once, which reopens the duplicate window right after a burst
(`COOKIEBOT.py:44-46`). This is a real LRU: eviction is oldest-first, so the
recent window is never lost.
"""


import cython
from blake3 import blake3

COMPILED: bool = cython.compiled


@cython.cclass
class RecentIds:
    """Fixed-capacity LRU of seen ids. `seen()` is O(1) and allocation-free in steady state."""

    capacity: cython.Py_ssize_t
    _ids: set
    _order: list
    _head: cython.Py_ssize_t

    def __init__(self, capacity: int = 65536) -> None:
        if capacity < 1:
            raise ValueError("capacity must be >= 1")
        self.capacity = capacity
        self._ids = set()
        self._order = [0] * capacity
        self._head = 0

    @cython.ccall
    def seen(self, update_id: cython.longlong) -> cython.bint:
        """True if this id was already recorded. Records it as a side effect."""
        ids: set = self._ids
        order: list = self._order
        head: cython.Py_ssize_t = self._head
        if update_id in ids:
            return True
        if len(ids) >= self.capacity:
            ids.discard(order[head])
        order[head] = update_id
        ids.add(update_id)
        head += 1
        self._head = 0 if head >= self.capacity else head
        return False

    def __len__(self) -> int:
        return len(self._ids)

    def __contains__(self, update_id: int) -> bool:
        return update_id in self._ids


def fingerprint(data: bytes) -> str:
    """blake3 content hash — dedupes media before it reaches the random/sticker DB.

    v1 stored every forwarded photo/video reference unconditionally
    (`SocialContent.py:191-196`), so the random pool filled with duplicates.
    """
    return blake3(data).hexdigest(length=16)


def fingerprint_parts(*parts: str) -> str:
    """Stable hash of identifying strings (file_unique_id, chat, sticker set...)."""
    # hot-types: ignore  blake3's hasher is a Rust extension object; Cython cannot
    # lower it to a C type, so an annotation here would satisfy the audit without
    # removing a single interpreter round trip.
    h = blake3()
    for p in parts:
        h.update(p.encode())
        h.update(b"\x1f")
    return h.hexdigest(length=16)


def idempotency_key(bot: str, update_id: int) -> str:
    """Cross-replica dedupe key. Gateway replicas share it via Valkey SET NX."""
    return "cb:upd:" + bot + ":" + str(update_id)

