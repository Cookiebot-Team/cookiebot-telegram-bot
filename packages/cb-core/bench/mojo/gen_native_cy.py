"""Generate cynative.py — the Cython counterpart of bench_native.mojo.

bench_native.mojo drives the workloads from Mojo, so no CPython call appears in
the timed loop. The Cython equivalent has to live in the *same compiled module*
as the classes it calls: a `@cython.ccall` method is only a direct C call from
inside the module that defines it. Across modules Cython falls back to a Python
attribute lookup, which is exactly the cost this benchmark exists to remove.

So the three hot modules are concatenated verbatim (no edits beyond dropping the
repeated `from __future__` line, which must be first in a file) and the driver is
appended. Logic is the sources', not a retyped copy.
"""

from __future__ import annotations

import pathlib

SOURCES = ["cooldowns.py", "dedupe.py", "textmatch.py"]

HEADER = '''"""Cython-native benchmark: hot modules + driver in one compiled unit.

Generated by gen_native_cy.py — do not edit. Every `@cython.ccall` call in the
driver below is a direct C call because the callee is defined in this same
module.
"""

from __future__ import annotations

from time import perf_counter_ns

import cython

'''

DRIVER = '''

# ------------------------------------------------------------------- driver

ROUNDS: cython.Py_ssize_t = 7


@cython.cfunc
def _bench_cooldowns(iterations: cython.Py_ssize_t) -> cython.double:
    best: cython.double = 1e30
    r: cython.Py_ssize_t
    i: cython.Py_ssize_t
    clock: cython.double
    sink: cython.Py_ssize_t
    ns: cython.double
    for r in range(ROUNDS):
        bucket: TokenBucket = TokenBucket(20.0, 5.0)
        window: SlidingWindow = SlidingWindow(5, 10.0)
        clock = 0.0
        sink = 0
        start = perf_counter_ns()
        for i in range(iterations):
            clock += 0.001
            if bucket.allow(clock) and window.exceeded(clock):
                sink += 1
        ns = (perf_counter_ns() - start) / iterations
        _keep(sink)
        if ns < best:
            best = ns
    return best


@cython.cfunc
def _bench_dedupe(iterations: cython.Py_ssize_t) -> cython.double:
    best: cython.double = 1e30
    r: cython.Py_ssize_t
    i: cython.Py_ssize_t
    sink: cython.Py_ssize_t
    ns: cython.double
    for r in range(ROUNDS):
        seen: RecentIds = RecentIds(65536)
        sink = 0
        start = perf_counter_ns()
        for i in range(iterations):
            if seen.seen(i):
                sink += 1
        ns = (perf_counter_ns() - start) / iterations
        _keep(sink)
        if ns < best:
            best = ns
    return best


@cython.cfunc
def _bench_textmatch(iterations: cython.Py_ssize_t) -> cython.double:
    samples: list = [
        "/dice@CookieMWbot 20",
        "/shippar @someone",
        "hello everyone, nothing to see here",
        "look https://bsky.app/profile/x/post/123 nice",
        "/d20",
    ]
    bot: str = "CookieMWbot"
    best: cython.double = 1e30
    r: cython.Py_ssize_t
    i: cython.Py_ssize_t
    sink: cython.Py_ssize_t
    ns: cython.double
    for r in range(ROUNDS):
        sink = 0
        start = perf_counter_ns()
        for i in range(iterations):
            parsed = parse_command(samples[i % 5], bot)
            if parsed is not None:
                sink += 1
        ns = (perf_counter_ns() - start) / iterations
        _keep(sink)
        if ns < best:
            best = ns
    return best


@cython.cfunc
def _bench_textmatch_one(sample: str, iterations: cython.Py_ssize_t) -> cython.double:
    """One fixed sample, so the per-shape cost is visible instead of averaged."""
    bot: str = "CookieMWbot"
    best: cython.double = 1e30
    r: cython.Py_ssize_t
    i: cython.Py_ssize_t
    sink: cython.Py_ssize_t
    ns: cython.double
    for r in range(ROUNDS):
        sink = 0
        start = perf_counter_ns()
        for i in range(iterations):
            parsed = parse_command(sample, bot)
            if parsed is not None:
                sink += 1
        ns = (perf_counter_ns() - start) / iterations
        _keep(sink)
        if ns < best:
            best = ns
    return best


@cython.cfunc
def _keep(value: cython.Py_ssize_t) -> cython.void:
    """Keep `value` observable so the optimiser cannot delete the loop body."""
    if value == -12345:
        print("unreachable", value)


def main() -> int:
    print("cython-native (no Python call in the loop) — best of", ROUNDS, "rounds\\n")
    print("cooldowns ", _bench_cooldowns(500_000), "ns/op")
    print("textmatch ", _bench_textmatch(200_000), "ns/op")
    print("dedupe    ", _bench_dedupe(500_000), "ns/op")
    print("")
    for sample in [
        "/dice@CookieMWbot 20",
        "/shippar @someone",
        "hello everyone, nothing to see here",
        "look https://bsky.app/profile/x/post/123 nice",
        "/d20",
    ]:
        print("  sample", repr(sample[:24]), _bench_textmatch_one(sample, 200_000), "ns/op")
    return 0
'''


def main() -> int:
    here = pathlib.Path(__file__).parent
    src = here / "cy"
    if not src.is_dir():
        src = here / ".." / ".." / "src" / "cb_core"
    parts = [HEADER]
    for name in SOURCES:
        text = (src / name).read_text()
        body = "\n".join(
            line for line in text.splitlines() if line != "from __future__ import annotations"
        )
        parts.append(f"\n# {'=' * 20} {name}\n\n{body}\n")
    parts.append(DRIVER)
    (here / "cynative.py").write_text("".join(parts))
    print("wrote cynative.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
